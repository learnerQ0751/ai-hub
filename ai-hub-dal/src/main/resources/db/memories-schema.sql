-- H2（PostgreSQL 兼容模式）测试 schema：与 Flyway V8 对齐。
-- 生产 DDL 见 db/migration/V8__memories.sql；本文件仅供测试初始化。

CREATE TABLE IF NOT EXISTS memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    memory_id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(128) NOT NULL,
    session_id VARCHAR(128),
    memory_type VARCHAR(16) NOT NULL DEFAULT 'SESSION',
    content TEXT NOT NULL,
    metadata JSONB,
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_memories_memory_id UNIQUE (memory_id)
);

CREATE INDEX IF NOT EXISTS idx_memories_scope
    ON memories (tenant_id, project_id, user_id, session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_memories_user_level
    ON memories (tenant_id, user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_memories_expires
    ON memories (expires_at);

CREATE TABLE IF NOT EXISTS memory_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(128) NOT NULL,
    session_id VARCHAR(128),
    operation VARCHAR(32) NOT NULL,
    deleted_count INTEGER NOT NULL,
    memory_ids JSONB,
    operator_key VARCHAR(128),
    reason VARCHAR(512),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_memory_audit_logs_audit_id UNIQUE (audit_id)
);
