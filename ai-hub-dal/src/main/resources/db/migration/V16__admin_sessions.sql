-- V16：控制台管理员会话与登录失败计数
-- 会话令牌只存 SHA-256 摘要；登录失败计数落库，保证多实例一致与重启不丢失。

CREATE TABLE IF NOT EXISTS admin_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    username VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_admin_sessions_token_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS idx_admin_sessions_expires
    ON admin_sessions (expires_at);

COMMENT ON TABLE admin_sessions IS '控制台管理员会话；只存令牌哈希';
COMMENT ON COLUMN admin_sessions.token_hash IS '会话令牌的 SHA-256 十六进制摘要';

CREATE TABLE IF NOT EXISTS admin_login_attempts (
    username VARCHAR(128) PRIMARY KEY,
    failed_count INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE admin_login_attempts IS '控制台登录失败计数与锁定截止时间';
