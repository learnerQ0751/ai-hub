-- V5：第 2 期 MCP 与 Prompt 中心基础表。
-- mcp_servers：MCP Server 注册表（REQ-2.1）
-- prompt_templates：Prompt 模板与版本（REQ-2.4）
-- call_logs：增加调用类型与目标名（REQ-2.3）

CREATE TABLE IF NOT EXISTS mcp_servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    transport VARCHAR(16) NOT NULL,
    endpoint VARCHAR(512),
    command VARCHAR(512),
    args JSONB,
    tenant_id VARCHAR(64),
    status VARCHAR(16) NOT NULL DEFAULT 'DOWN',
    last_health_at TIMESTAMP WITH TIME ZONE,
    metadata JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mcp_servers_server_id UNIQUE (server_id),
    CONSTRAINT uk_mcp_servers_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS prompt_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    version INTEGER NOT NULL,
    content TEXT NOT NULL,
    variables JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    tenant_id VARCHAR(64),
    created_by VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prompt_templates_name_version UNIQUE (name, version)
);

ALTER TABLE call_logs ADD COLUMN IF NOT EXISTS call_type VARCHAR(16) DEFAULT 'CHAT';
ALTER TABLE call_logs ADD COLUMN IF NOT EXISTS target_name VARCHAR(128);
