-- V13：审计日志（REQ-4.5）
-- 只追加：应用层不提供 update/delete；数据库再用触发器阻断篡改。

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL DEFAULT 'default',
    actor VARCHAR(128) NOT NULL,
    action VARCHAR(64) NOT NULL,
    target VARCHAR(256),
    before_state JSONB,
    after_state JSONB,
    trace_id VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE audit_logs IS '治理动作审计（只追加，不可修改/删除）';
COMMENT ON COLUMN audit_logs.actor IS 'master 或虚拟 Key 哈希';
COMMENT ON COLUMN audit_logs.before_state IS '变更前快照（脱敏，不含密钥）';
COMMENT ON COLUMN audit_logs.after_state IS '变更后快照（脱敏，不含密钥）';

CREATE INDEX IF NOT EXISTS idx_audit_logs_tenant_created
    ON audit_logs (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action_created
    ON audit_logs (action, created_at DESC);

-- 数据库层不可变：任何 UPDATE/DELETE 直接报错。
CREATE OR REPLACE FUNCTION audit_logs_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_logs_immutable ON audit_logs;
CREATE TRIGGER trg_audit_logs_immutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_immutable();
