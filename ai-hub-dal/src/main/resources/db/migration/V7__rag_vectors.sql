-- V7：第 3 期 RAG 向量存储（REQ-3.2）
-- 依赖 pgvector 扩展；本地 docker-compose 使用 pgvector/pgvector:pg16。
-- 向量维度与默认模型 all-minilm-l6-v2 对齐（384）；切换不同维度模型需迁移本列。

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS rag_vectors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chunk_id VARCHAR(96) NOT NULL,
    doc_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    embedding_model VARCHAR(128) NOT NULL,
    embedding_dimension INTEGER NOT NULL,
    embedding vector(384) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rag_vectors_chunk_id UNIQUE (chunk_id)
);

COMMENT ON TABLE rag_vectors IS 'RAG 切片向量；按 chunk_id 幂等覆盖，按 project_id + 模型版本隔离';
COMMENT ON COLUMN rag_vectors.embedding_model IS '生成向量的模型标识（含版本）';
COMMENT ON COLUMN rag_vectors.embedding IS 'pgvector 向量；维度固定 384';

CREATE INDEX IF NOT EXISTS idx_rag_vectors_doc
    ON rag_vectors (doc_id);
CREATE INDEX IF NOT EXISTS idx_rag_vectors_project_model
    ON rag_vectors (project_id, embedding_model);
-- HNSW cosine 索引：REQ-3.3 检索使用 ORDER BY embedding <=> query
CREATE INDEX IF NOT EXISTS idx_rag_vectors_hnsw
    ON rag_vectors USING hnsw (embedding vector_cosine_ops);
