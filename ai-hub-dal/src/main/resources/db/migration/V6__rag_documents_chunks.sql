-- V6：第 3 期 RAG 文档接入（REQ-3.1）
-- rag_documents：文档元数据 + 原始文件（解析失败也保留）
-- rag_chunks：段落优先切分后的切片；向量在 V7 的 rag_vectors 中

CREATE TABLE IF NOT EXISTS rag_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    source VARCHAR(512) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    size_bytes BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    raw_content BYTEA,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    index_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    embedding_model VARCHAR(128),
    embedding_dimension INTEGER,
    embedding_duration_ms BIGINT,
    embedding_cost NUMERIC(18, 8) NOT NULL DEFAULT 0,
    error_message VARCHAR(1024),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rag_documents_doc_id UNIQUE (doc_id),
    CONSTRAINT uk_rag_documents_project_hash UNIQUE (project_id, content_hash)
);

COMMENT ON TABLE rag_documents IS 'RAG 文档元数据；原始文件落库，解析失败也保留';
COMMENT ON COLUMN rag_documents.content_hash IS '原始文件 SHA-256；同项目内唯一';
COMMENT ON COLUMN rag_documents.raw_content IS '原始文件字节；多实例一致，不依赖本机目录';
COMMENT ON COLUMN rag_documents.index_status IS 'PENDING/PROCESSING/READY/FAILED';
COMMENT ON COLUMN rag_documents.embedding_cost IS '向量化成本；本地模型为 0';

CREATE INDEX IF NOT EXISTS idx_rag_documents_project
    ON rag_documents (project_id, created_at DESC);

CREATE TABLE IF NOT EXISTS rag_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chunk_id VARCHAR(96) NOT NULL,
    doc_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    char_count INTEGER NOT NULL,
    source VARCHAR(512) NOT NULL,
    index_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    embedding_model VARCHAR(128),
    embedding_dimension INTEGER,
    error_message VARCHAR(1024),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rag_chunks_chunk_id UNIQUE (chunk_id)
);

COMMENT ON TABLE rag_chunks IS 'RAG 切片：段落优先切分，超长段落定长 + overlap';
COMMENT ON COLUMN rag_chunks.chunk_id IS '确定性切片 ID：{doc_id}-{序号}';
COMMENT ON COLUMN rag_chunks.index_status IS 'PENDING/PROCESSING/READY/FAILED';

CREATE INDEX IF NOT EXISTS idx_rag_chunks_doc
    ON rag_chunks (doc_id, chunk_index);
CREATE INDEX IF NOT EXISTS idx_rag_chunks_project
    ON rag_chunks (project_id);
