-- V1：虚拟 Key 表（REQ-1.3）
-- models / metadata 使用 JSONB；key_hash 只存 SHA-256 摘要，永不存明文。
-- 保留 IF NOT EXISTS：兼容已存在的本地库（Flyway baseline-version=0）。
CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_hash VARCHAR(64) NOT NULL,
    models JSONB NOT NULL,
    spend NUMERIC(18, 8) NOT NULL DEFAULT 0,
    max_budget NUMERIC(18, 8),
    rpm_limit INTEGER,
    tpm_limit INTEGER,
    expires_at TIMESTAMP WITH TIME ZONE,
    blocked BOOLEAN NOT NULL DEFAULT FALSE,
    metadata JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_api_keys_key_hash UNIQUE (key_hash)
);

COMMENT ON TABLE api_keys IS '虚拟 API Key（仅存哈希）';
COMMENT ON COLUMN api_keys.key_hash IS 'SHA-256 十六进制摘要';
COMMENT ON COLUMN api_keys.models IS '模型别名白名单 JSON 数组；空数组表示不限制';
COMMENT ON COLUMN api_keys.spend IS '已消费金额';
COMMENT ON COLUMN api_keys.blocked IS '是否封禁';
