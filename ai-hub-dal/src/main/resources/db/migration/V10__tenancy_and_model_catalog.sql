-- V10：第 4 期多租户贯穿（REQ-4.1）
-- 1) 租户/项目/项目授权表；2) api_keys 绑定 (tenant_id, project_id)；
-- 3) 资源表补 tenant_id 并把唯一约束改为租户内唯一；
-- 4) 模型别名/部署实例表（别名配置从 YAML 迁到 DB，REQ-4.1/4.4）。

CREATE TABLE IF NOT EXISTS tenants (
    tenant_id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    tenant_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_projects PRIMARY KEY (tenant_id, project_id)
);

COMMENT ON TABLE tenants IS '租户（组织级隔离边界）';
COMMENT ON TABLE projects IS '项目（租户内隔离边界）';

-- 显式跨项目授权：默认隔离，只有授权后同租户项目可共享记忆/知识库。
CREATE TABLE IF NOT EXISTS project_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    source_project_id VARCHAR(64) NOT NULL,
    target_project_id VARCHAR(64) NOT NULL,
    resource_type VARCHAR(16) NOT NULL DEFAULT 'MEMORY',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_project_authorizations UNIQUE
        (tenant_id, source_project_id, target_project_id, resource_type)
);

COMMENT ON TABLE project_authorizations IS '项目级显式授权（记忆/知识库跨项目共享）';
COMMENT ON COLUMN project_authorizations.resource_type IS 'MEMORY / KNOWLEDGE / ALL';

INSERT INTO tenants (tenant_id, name) VALUES ('default', '默认租户')
    ON CONFLICT (tenant_id) DO NOTHING;
INSERT INTO projects (tenant_id, project_id, name) VALUES ('default', 'default', '默认项目')
    ON CONFLICT (tenant_id, project_id) DO NOTHING;

-- 虚拟 Key 绑定租户/项目；历史 Key 保持 NULL，访问租户资源时返回 403。
ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64);
ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS project_id VARCHAR(64);
CREATE INDEX IF NOT EXISTS idx_api_keys_tenant ON api_keys (tenant_id, project_id);
COMMENT ON COLUMN api_keys.tenant_id IS 'Key 绑定租户；只能来自 Key，禁止请求参数覆盖';
COMMENT ON COLUMN api_keys.project_id IS 'Key 绑定项目';

-- 调用日志补项目与 trace。
ALTER TABLE call_logs ADD COLUMN IF NOT EXISTS project_id VARCHAR(64);
ALTER TABLE call_logs ADD COLUMN IF NOT EXISTS trace_id VARCHAR(64);
UPDATE call_logs SET trace_id = request_id WHERE trace_id IS NULL;
CREATE INDEX IF NOT EXISTS idx_call_logs_tenant_created
    ON call_logs (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_call_logs_trace ON call_logs (trace_id);

-- RAG 文档/切片/向量补租户，唯一约束收敛到租户内。
ALTER TABLE rag_documents ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64) NOT NULL DEFAULT 'default';
ALTER TABLE rag_chunks ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64) NOT NULL DEFAULT 'default';
ALTER TABLE rag_vectors ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64) NOT NULL DEFAULT 'default';

ALTER TABLE rag_documents DROP CONSTRAINT IF EXISTS uk_rag_documents_project_hash;
ALTER TABLE rag_documents ADD CONSTRAINT uk_rag_documents_tenant_project_hash
    UNIQUE (tenant_id, project_id, content_hash);
CREATE INDEX IF NOT EXISTS idx_rag_documents_tenant_project
    ON rag_documents (tenant_id, project_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rag_chunks_tenant_project
    ON rag_chunks (tenant_id, project_id);
CREATE INDEX IF NOT EXISTS idx_rag_vectors_tenant_project_model
    ON rag_vectors (tenant_id, project_id, embedding_model);

-- Prompt 名称在租户内唯一。
UPDATE prompt_templates SET tenant_id = 'default' WHERE tenant_id IS NULL;
ALTER TABLE prompt_templates ALTER COLUMN tenant_id SET DEFAULT 'default';
ALTER TABLE prompt_templates DROP CONSTRAINT IF EXISTS uk_prompt_templates_name_version;
ALTER TABLE prompt_templates ADD CONSTRAINT uk_prompt_templates_tenant_name_version
    UNIQUE (tenant_id, name, version);

-- MCP Server 名称在租户内唯一。
UPDATE mcp_servers SET tenant_id = 'default' WHERE tenant_id IS NULL;
ALTER TABLE mcp_servers ALTER COLUMN tenant_id SET DEFAULT 'default';
ALTER TABLE mcp_servers DROP CONSTRAINT IF EXISTS uk_mcp_servers_name;
ALTER TABLE mcp_servers ADD CONSTRAINT uk_mcp_servers_tenant_name UNIQUE (tenant_id, name);

-- 模型别名与部署实例（多对多），别名配置由 YAML 迁移到 DB。
CREATE TABLE IF NOT EXISTS model_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias VARCHAR(128) NOT NULL,
    tenant_id VARCHAR(64),
    description VARCHAR(512),
    fallbacks JSONB,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_model_aliases_alias UNIQUE (alias)
);

CREATE TABLE IF NOT EXISTS model_deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_key VARCHAR(64) NOT NULL,
    api_base VARCHAR(512) NOT NULL,
    api_key_cipher TEXT,
    upstream_model VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_model_deployments_key UNIQUE (deployment_key)
);

CREATE TABLE IF NOT EXISTS model_alias_deployments (
    alias_id BIGINT NOT NULL,
    deployment_id BIGINT NOT NULL,
    weight INTEGER NOT NULL DEFAULT 1,
    priority INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (alias_id, deployment_id)
);

CREATE TABLE IF NOT EXISTS model_alias_keys (
    alias_id BIGINT NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    PRIMARY KEY (alias_id, key_hash)
);

COMMENT ON TABLE model_aliases IS '模型别名（对外名）；tenant_id 为空表示全局别名';
COMMENT ON TABLE model_deployments IS '上游部署实例（api_base + 真实模型 + 凭证密文）';
COMMENT ON TABLE model_alias_deployments IS '别名↔部署多对多（权重/优先级）';
COMMENT ON TABLE model_alias_keys IS '别名↔虚拟 Key 多对多（白名单来源）';
COMMENT ON COLUMN model_deployments.api_key_cipher IS '上游 Key 密文，永不通过管理接口回显';
