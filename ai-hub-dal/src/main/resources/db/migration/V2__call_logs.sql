-- V2：调用日志与 Token 计量（REQ-1.5）
-- 每次聊天补全调用落一条；key_id 存虚拟 Key 的 SHA-256，master 调用为 NULL。
-- cost 精度与 api_keys.spend 一致，便于预算与成本看板聚合。
CREATE TABLE IF NOT EXISTS call_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL,
    key_id VARCHAR(64),
    model_alias VARCHAR(128) NOT NULL,
    deployment_model VARCHAR(128),
    prompt_tokens INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    total_tokens INTEGER NOT NULL DEFAULT 0,
    cost NUMERIC(18, 8) NOT NULL DEFAULT 0,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    status INTEGER NOT NULL,
    tenant_id VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_call_logs_request_id ON call_logs (request_id);
CREATE INDEX IF NOT EXISTS idx_call_logs_key_created ON call_logs (key_id, created_at);

COMMENT ON TABLE call_logs IS 'LLM 调用日志与 Token 计量';
COMMENT ON COLUMN call_logs.request_id IS '入口生成的请求追踪 ID';
COMMENT ON COLUMN call_logs.key_id IS '虚拟 Key 的 SHA-256；master 调用为空';
COMMENT ON COLUMN call_logs.model_alias IS '请求使用的模型别名';
COMMENT ON COLUMN call_logs.deployment_model IS '路由到的上游真实模型名';
COMMENT ON COLUMN call_logs.cost IS '按价格表计算的成本';
COMMENT ON COLUMN call_logs.status IS '返回给客户端的 HTTP 状态码';
COMMENT ON COLUMN call_logs.tenant_id IS '租户 ID；本期未启用';
