-- V14：控制面写请求幂等键（REQ-5.2）
-- 客户端通过 Idempotency-Key 头重放同一请求时，直接返回首次响应，不重复执行。

CREATE TABLE IF NOT EXISTS idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_status INTEGER,
    response_content_type VARCHAR(128),
    response_body TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_idempotency_keys_key UNIQUE (idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_idempotency_keys_created
    ON idempotency_keys (created_at);

COMMENT ON TABLE idempotency_keys IS '控制面写请求幂等键；同键同请求返回首次响应';
COMMENT ON COLUMN idempotency_keys.request_hash IS 'SHA-256(method + path + body)';
