-- V11：全链路 Trace（REQ-4.2）
-- trace_id 与 request_id 同源；一次请求按分段写事件，异步落库不阻塞响应。

CREATE TABLE IF NOT EXISTS trace_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL DEFAULT 'default',
    project_id VARCHAR(64),
    key_id VARCHAR(64),
    segment VARCHAR(32) NOT NULL,
    name VARCHAR(128),
    status INTEGER NOT NULL DEFAULT 0,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    payload JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE trace_events IS '全链路分段事件（gateway/model/rag/mcp）';
COMMENT ON COLUMN trace_events.segment IS 'gateway / model / rag / mcp';
COMMENT ON COLUMN trace_events.payload IS '分段摘要（查询长度、命中 id、tokens、cost 等），不含正文';

CREATE INDEX IF NOT EXISTS idx_trace_events_trace ON trace_events (trace_id, id);
CREATE INDEX IF NOT EXISTS idx_trace_events_tenant_created
    ON trace_events (tenant_id, created_at DESC);
