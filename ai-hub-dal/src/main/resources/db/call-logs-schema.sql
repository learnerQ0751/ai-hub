-- 测试用 call_logs 表（H2 PostgreSQL 模式）；与 V2__call_logs.sql 保持同构。
CREATE TABLE IF NOT EXISTS call_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(64) NOT NULL,
    key_id VARCHAR(64),
    model_alias VARCHAR(128) NOT NULL,
    deployment_model VARCHAR(128),
    prompt_tokens INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    total_tokens INTEGER NOT NULL DEFAULT 0,
    cost NUMERIC(18, 8) NOT NULL DEFAULT 0,
    latency_ms BIGINT NOT NULL DEFAULT 0,
    status INTEGER NOT NULL,
    tenant_id VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_call_logs_request_id ON call_logs (request_id);
CREATE INDEX IF NOT EXISTS idx_call_logs_key_created ON call_logs (key_id, created_at);
